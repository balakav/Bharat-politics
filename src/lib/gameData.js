// Sort RMC constituency/seat groups in proper order:
// Nagaradhyaksh first, then Ward 1 A, Ward 1 B, Ward 2 A, Ward 2 B, ...
export function sortRMCSeatGroups(groups) {
  return groups.sort((a, b) => {
    const aIsND = (a.seat_type === 'Nagaradhyaksh') || (a.name && a.name.includes('Nagaradhyaksh'));
    const bIsND = (b.seat_type === 'Nagaradhyaksh') || (b.name && b.name.includes('Nagaradhyaksh'));
    if (aIsND && !bIsND) return -1;
    if (!aIsND && bIsND) return 1;
    if (aIsND && bIsND) return 0;

    const getWardNum = (g) => {
      const match = (g.constituency || g.name || '').match(/(\d+)/);
      return match ? parseInt(match[1]) : 999;
    };
    const aNum = getWardNum(a);
    const bNum = getWardNum(b);
    if (aNum !== bNum) return aNum - bNum;

    const aSeat = a.seat_type || '';
    const bSeat = b.seat_type || '';
    if (aSeat === 'Seat A' && bSeat === 'Seat B') return -1;
    if (aSeat === 'Seat B' && bSeat === 'Seat A') return 1;
    return 0;
  });
}

